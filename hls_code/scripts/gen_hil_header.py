"""
gen_hil_header.py
-----------------
Packs the hardware-in-the-loop windows (hil_verification_samples/, written by emg_common.export_hls) into
weights/hil_windows.h, so the Vitis testbench can run all of them in C simulation and co-simulation without
reading files (Vitis runs those from build folders where relative file paths break).

  hil_input[N][IN_WORDS]       real preprocessed EMG windows, channel-major (the IP's input layout)
  hil_fixed[N][NUM_OUTPUTS]    numpy fixed-point outputs [abs | delta_std]: what the IP must return
  hil_float[N][NUM_OUTPUTS]    float-model outputs, for information

install_export.py runs this automatically. Usage: python scripts/gen_hil_header.py [hil_dir] [out_header]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load(path):
    with open(path) as f:
        return [float(v) for v in f.read().split()]


def generate(hil_dir, out_path):
    wins = []
    for i in range(1000):
        p = os.path.join(hil_dir, f'sample_{i:03d}_')
        if not os.path.exists(p + 'input.txt'):
            break
        if not os.path.exists(p + 'fixed.txt'):
            sys.exit(f'{p}fixed.txt missing: the samples come from an export older than the fixed-point references; re-export')
        out = load(p + 'output.txt') + (load(p + 'delta.txt') if os.path.exists(p + 'delta.txt') else [])
        wins.append((load(p + 'input.txt'), load(p + 'fixed.txt'), out))
    if not wins:
        sys.exit(f'no sample_*_input.txt in {hil_dir}')
    n_in, n_out = len(wins[0][0]), len(wins[0][1])
    assert all(len(a) == n_in and len(b) == n_out and len(c) == n_out for a, b, c in wins), 'inconsistent sample sizes'
    lit = lambda x: (lambda t: t if any(c in t for c in '.en') else t + '.0')(f'{x:.7g}') + 'f'   # 0 -> 0.0f
    fmt = lambda xs: ', '.join(lit(x) for x in xs)
    with open(out_path, 'w') as f:
        f.write('#ifndef HIL_WINDOWS_H\n#define HIL_WINDOWS_H\n')
        f.write(f'// generated by scripts/gen_hil_header.py from {os.path.basename(os.path.normpath(hil_dir))}/: '
                f'{len(wins)} real test windows\n#include "../config.h"\n\n')
        f.write(f'#define HIL_N {len(wins)}\n')
        f.write(f'#if IN_WORDS != {n_in} || NUM_OUTPUTS != {n_out}\n#error "hil_windows.h does not match the installed model: '
                're-run scripts/gen_hil_header.py"\n#endif\n\n')
        for name, k in (('hil_input', 0), ('hil_fixed', 1), ('hil_float', 2)):
            f.write(f'static const float {name}[HIL_N][{n_in if k == 0 else n_out}] = {{\n')
            for w in wins:
                f.write('  {' + fmt(w[k]) + '},\n')
            f.write('};\n\n')
        f.write('#endif // HIL_WINDOWS_H\n')
    return len(wins)


if __name__ == '__main__':
    hil = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, '..', '..', 'hil_verification_samples')
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, '..', 'weights', 'hil_windows.h')
    n = generate(hil, out)
    print(f'{out}: {n} windows ({os.path.getsize(out) / 1e6:.1f} MB)')
